// Keep the editable Dawn styles intact; split only between complete CSS rules for inline_asset_content's 15 KB limit.
import { readFile, writeFile } from 'node:fs/promises';
const limit = 14000;
for (const name of ['base', 'brand', 'section-main-product', 'component-facets']) {
  const css = await readFile(`assets/${name}.css`, 'utf8');
  const boundaries = [];
  let depth = 0, quote = '', comment = false;
  for (let i = 0; i < css.length; i++) {
    const c = css[i], next = css[i + 1];
    if (comment) { if (c === '*' && next === '/') { comment = false; i++; } continue; }
    if (quote) { if (c === '\\') i++; else if (c === quote) quote = ''; continue; }
    if (c === '/' && next === '*') { comment = true; i++; continue; }
    if (c === '"' || c === "'") { quote = c; continue; }
    if (c === '{') depth++;
    if (c === '}') { depth--; if (depth === 0) boundaries.push(i + 1); }
    if (c === ';' && depth === 0) boundaries.push(i + 1);
  }
  if (depth || quote || comment) throw new Error(`Unbalanced ${name} CSS`);
  boundaries.push(css.length);
  const chunks = [];
  let start = 0;
  while (start < css.length) {
    const end = boundaries.filter(end => end > start && Buffer.byteLength(css.slice(start, end)) < limit).at(-1);
    if (!end) throw new Error(`A ${name} rule exceeds the inline limit`);
    chunks.push(css.slice(start, end));
    start = end;
  }
  for (const [i, chunk] of chunks.entries()) await writeFile(`assets/perf-${name}-${i + 1}.css`, chunk);
  const lines = chunks.map((_, i) => `{{- 'perf-${name}-${i + 1}.css' | inline_asset_content | replace: './sparkle.gif', sparkle_url -}}`).join('\n');
  await writeFile(`snippets/perf-${name}-css.liquid`, `{% doc %}\n  Generated by scripts/critical-css.mjs from assets/${name}.css. Preserve rule order and relative asset URLs.\n{% enddoc %}\n{%- assign sparkle_url = 'sparkle.gif' | asset_url -%}\n<style>\n${lines}\n</style>\n`);
}
